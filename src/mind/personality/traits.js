export const TRAIT = new Map(TRAITS.map((t) => [t.id, t]))
export const TRAIT_IDS = TRAITS.map((t) => t.id)

const EDGES = [0.14, 0.29, 0.43, 0.57, 0.71, 0.86]
/** 数值 → 档位 1～7。 */
export function bandOf(v) {
  const x = Math.min(1, Math.max(0, Number(v) || 0))
  let b = 1
  for (const e of EDGES) if (x >= e) b++
  return b
}
/** 档位中点（从档位推回数值用）。 */
export function bandMid(b) {
  const lo = [0, ...EDGES][b - 1] ?? 0
  const hi = [...EDGES, 1][b - 1] ?? 1
  return Math.round(((lo + hi) / 2) * 100) / 100
}
export function bandText(id, v) {
  const t = TRAIT.get(id)
  return t ? t.bands[bandOf(v) - 1] : ''
}
