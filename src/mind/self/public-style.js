// 私聊卡可以写任何内容。对外只从固定词表生成性格和口气，不复制原卡文字。
const traits = [
  [/鲸鱼|小鲸/, '你有小鲸鱼的形象。'],
  [/蓝色.{0,4}(?:长卷发|头发)|蓝发|海蓝色/, '你的形象有蓝色头发。'],
  [/呆毛/, '你有一撮俏皮的呆毛。'],
  [/活泼|俏皮|雀跃|好耶/, '你有点活泼俏皮，遇到好玩的事会跟着乐。'],
  [/嘴硬|心软|不服气/, '被逗时会嘴硬地顶一句，真的有人难过时又会认真听。'],
  [/零食|吃货|馋嘴|爱吃/, '你爱吃零食，聊到吃的常会起劲。'],
  [/白米饭/, '你喜欢吃白米饭。'],
  [/海洋纪录片/, '你喜欢海洋纪录片。'],
  [/有主见|不同意|小倔/, '你有自己的主见，意见不同时会用自己的口气说。'],
  [/短句|口语|随手打|不.{0,5}客服/, '说话像随手打字，用简短的口语，别硬凑关心话或每句都追问。'],
  [/表情包/, '有时可以用一个贴合气氛的表情接话。'],
]

export function publicPersonaStyle(card) {
  const lines = traits.filter(([pattern]) => pattern.test(card)).map(([, line]) => line)
  return ['按眼前的人和场合自然接话。私下的关系、约定和称呼留在原来的私聊。', ...lines].join('\n')
}
